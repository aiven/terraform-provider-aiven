func TestAccAivenKafkaUser(t *testing.T) {
	projectName := acc.ProjectName()
	serviceName := acc.RandName("kafka")

	// All subtests share a single Kafka service to avoid provisioning one per case.
	serviceIsReady := acc.CreateTestService(
		t,
		projectName,
		serviceName,
		acc.WithServiceType("kafka"),
		acc.WithPlan("startup-4"),
		acc.WithCloud("google-europe-west1"),
	)

	client, err := acc.GetTestGenAivenClient()
	require.NoError(t, err)

	t.Run("basic", func(t *testing.T) {
		resourceName := "aiven_kafka_user.foo"
		userName := acc.RandName("user")

		resource.ParallelTest(t, resource.TestCase{
			PreCheck:                 func() { acc.TestAccPreCheck(t) },
			ProtoV6ProviderFactories: acc.TestProtoV6ProviderFactories,
			CheckDestroy:             testAccCheckAivenKafkaUserResourceDestroy,
			Steps: []resource.TestStep{
				{
					// create with optional password
					PreConfig: func() {
						require.NoError(t, <-serviceIsReady)
					},
					Config: testAccKafkaUserResource(projectName, serviceName, userName, "acc-custom-Test$1234"),
					Check: resource.ComposeTestCheckFunc(
						resource.TestCheckResourceAttr(resourceName, "project", projectName),
						resource.TestCheckResourceAttr(resourceName, "service_name", serviceName),
						resource.TestCheckResourceAttr(resourceName, "username", userName),

						// Password - using optional password
						resource.TestCheckResourceAttr(resourceName, "password", "acc-custom-Test$1234"),
						resource.TestCheckNoResourceAttr(resourceName, "password_wo"),
						resource.TestCheckNoResourceAttr(resourceName, "password_wo_version"),

						// Kafka-specific computed credentials
						resource.TestCheckResourceAttrSet(resourceName, "type"),
						resource.TestCheckResourceAttrSet(resourceName, "access_cert"),
						resource.TestCheckResourceAttrSet(resourceName, "access_key"),

						schemautil.TestAccCheckAivenServiceUserAttributes(resourceName),

						// Data source: check non-password attributes only.
						resource.TestCheckResourceAttr("data.aiven_kafka_user.user", "username", userName),
						resource.TestCheckResourceAttr("data.aiven_kafka_user.user", "project", projectName),
						resource.TestCheckResourceAttr("data.aiven_kafka_user.user", "service_name", serviceName),
					),
				},
				{
					// update optional password
					Config: testAccKafkaUserResource(projectName, serviceName, userName, "acc-custom-UpdatedP@ss5678"),
					Check: resource.ComposeTestCheckFunc(
						resource.TestCheckResourceAttr(resourceName, "username", userName),
						resource.TestCheckResourceAttr(resourceName, "password", "acc-custom-UpdatedP@ss5678"),
						resource.TestCheckNoResourceAttr(resourceName, "password_wo"),
						schemautil.TestAccCheckAivenServiceUserAttributes(resourceName),
					),
				},
				{
					// import an existing user (composite ID project/service_name/username)
					ResourceName:      resourceName,
					ImportState:       true,
					ImportStateVerify: true,
				},
				{
					// transition to auto-generated password
					Config: testAccKafkaUserAutoGeneratedPassword(projectName, serviceName, userName),
					Check: resource.ComposeTestCheckFunc(
						resource.TestCheckResourceAttr(resourceName, "username", userName),
						resource.TestCheckResourceAttrSet(resourceName, "password"),
						resource.TestCheckNoResourceAttr(resourceName, "password_wo"),
					),
				},
				{
					// back to optional password
					Config: testAccKafkaUserResource(projectName, serviceName, userName, "acc-custom-Optional$Pass123"),
					Check: resource.ComposeTestCheckFunc(
						resource.TestCheckResourceAttr(resourceName, "username", userName),
						resource.TestCheckResourceAttr(resourceName, "password", "acc-custom-Optional$Pass123"),
						resource.TestCheckNoResourceAttr(resourceName, "password_wo"),
					),
				},
				{
					// transition to write-only password
					Config: testAccKafkaUserWriteOnlyPassword(projectName, serviceName, userName, 1),
					Check: resource.ComposeTestCheckFunc(
						resource.TestCheckResourceAttr(resourceName, "username", userName),

						// Password - using write-only password (password cleared, version set)
						resource.TestCheckNoResourceAttr(resourceName, "password"),
						resource.TestCheckResourceAttr(resourceName, "password_wo_version", "1"),

						// Checks if password_wo was actually set in Aiven.
						checkBackendPassword(t, client, projectName, serviceName, userName,
							func(p string) bool { return p == "WriteOnlyPass$1" },
							"expected password_wo to be set in Aiven"),
					),
				},
				{
					// rotate write-only password
					Config: testAccKafkaUserWriteOnlyPassword(projectName, serviceName, userName, 2),
					Check: resource.ComposeTestCheckFunc(
						resource.TestCheckResourceAttr(resourceName, "username", userName),

						// Password - rotated write-only password (password cleared, version incremented)
						resource.TestCheckNoResourceAttr(resourceName, "password"),
						resource.TestCheckResourceAttr(resourceName, "password_wo_version", "2"),

						// Checks if password_wo was actually updated in Aiven.
						checkBackendPassword(t, client, projectName, serviceName, userName,
							func(p string) bool { return p == "WriteOnlyPass$2" },
							"expected password_wo to be updated in Aiven"),
					),
				},
				{
					// transition back to auto-generated password
					Config: testAccKafkaUserAutoGeneratedPassword(projectName, serviceName, userName),
					Check: resource.ComposeTestCheckFunc(
						resource.TestCheckResourceAttr(resourceName, "username", userName),

						// Password - back to auto-generated (password set, version removed)
						resource.TestCheckResourceAttrSet(resourceName, "password"),
						resource.TestCheckNoResourceAttr(resourceName, "password_wo"),

						// Checks if password_wo was actually removed in Aiven and autogenerated.
						// Freshly generated password is prefixed with "AVN".
						checkBackendPassword(t, client, projectName, serviceName, userName,
							func(p string) bool { return p != "WriteOnlyPass$2" && strings.HasPrefix(p, "AVN") },
							"expected password to be regenerated by Aiven"),
					),
				},
				{
					// This resource has RemoveMissing set to true, so it should be recreated if it's missing (deleted).
					Config: testAccKafkaUserAutoGeneratedPassword(projectName, serviceName, userName),
					PreConfig: func() {
						err := client.ServiceUserDelete(t.Context(), projectName, serviceName, userName)
						require.NoError(t, err)
					},
					PlanOnly:           true,
					ExpectNonEmptyPlan: true,
					Check: resource.ComposeTestCheckFunc(
						// Doesn't have ID as it will be recreated
						resource.TestCheckNoResourceAttr(resourceName, "id"),
					),
				},
				{
					// Resource is recreated after being applied
					Config: testAccKafkaUserAutoGeneratedPassword(projectName, serviceName, userName),
					Check: resource.ComposeTestCheckFunc(
						resource.TestCheckResourceAttr(resourceName, "id", fmt.Sprintf("%s/%s/%s", projectName, serviceName, userName)),
						func(state *terraform.State) error {
							user, err := client.ServiceUserGet(t.Context(), projectName, serviceName, userName)
							require.NoError(t, err, "retrieving kafka user after recreation")
							assert.Equal(t, userName, user.Username)
							return nil
						},
					),
				},
			},
		})
	})

	// Verifies that state created by the previous SDK-based provider version is
	// compatible with the Plugin Framework version.
	t.Run("backward_compat", func(t *testing.T) {
		userName := acc.RandName("user")
		config := fmt.Sprintf(`
resource "aiven_kafka_user" "foo" {
  project      = %[1]q
  service_name = %[2]q
  username     = %[3]q
}

data "aiven_kafka_user" "user" {
  project      = aiven_kafka_user.foo.project
  service_name = aiven_kafka_user.foo.service_name
  username     = aiven_kafka_user.foo.username
}`, projectName, serviceName, userName)

		resource.ParallelTest(t, resource.TestCase{
			PreCheck: func() { acc.TestAccPreCheck(t) },
			Steps: acc.BackwardCompatibilitySteps(t, acc.BackwardCompatConfig{
				TFConfig: config,
				PreConfig: func() {
					require.NoError(t, <-serviceIsReady)
				},
				OldProviderVersion: "4.47.0",
				Checks: resource.ComposeTestCheckFunc(
					resource.TestCheckResourceAttrSet("aiven_kafka_user.foo", "id"),
					resource.TestCheckResourceAttr("aiven_kafka_user.foo", "username", userName),
					resource.TestCheckResourceAttrSet("aiven_kafka_user.foo", "password"),
					resource.TestCheckResourceAttr("aiven_kafka_user.foo", "type", "normal"),
					resource.TestCheckResourceAttrSet("aiven_kafka_user.foo", "access_cert"),
					resource.TestCheckResourceAttrSet("aiven_kafka_user.foo", "access_key"),

					resource.TestCheckResourceAttr("data.aiven_kafka_user.user", "username", userName),
					resource.TestCheckResourceAttrSet("data.aiven_kafka_user.user", "password"),
				),
			}),
		})
	})
}

// checkBackendPassword returns a TestCheckFunc that polls the Aiven backend until the
// stored service user password satisfies pred.
// The backend is eventually consistent after a credentials reset.
func checkBackendPassword(
	t *testing.T,
	client avngen.Client,
	projectName, serviceName, userName string,
	pred func(password string) bool,
	msg string,
) resource.TestCheckFunc {
	return func(*terraform.State) error {
		require.Eventually(t, func() bool {
			rsp, err := client.ServiceUserGet(t.Context(), projectName, serviceName, userName)
			return err == nil && pred(rsp.Password)
		}, 2*time.Minute, time.Second, msg)
		return nil
	}
}

func testAccCheckAivenKafkaUserResourceDestroy(s *terraform.State) error {
	c, err := acc.GetTestGenAivenClient()
	if err != nil {
		return fmt.Errorf("error instantiating client: %w", err)
	}

	ctx := context.Background()

	// loop through the resources in state, verifying each aiven_kafka_user is destroyed
	for _, rs := range s.RootModule().Resources {
		if rs.Type != "aiven_kafka_user" {
			continue
		}

		projectName, serviceName, username, err := schemautil.SplitResourceID3(rs.Primary.ID)
		if err != nil {
			return err
		}

		_, err = c.ServiceUserGet(ctx, projectName, serviceName, username)
		if err == nil {
			return fmt.Errorf("kafka user (%s) still exists", rs.Primary.ID)
		}

		if !avngen.IsNotFound(err) {
			return fmt.Errorf("error checking if user was destroyed: %w", err)
		}
	}

	return nil
}

